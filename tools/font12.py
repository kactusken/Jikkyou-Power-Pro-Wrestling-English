CHARS = [' '] + [chr(c) for c in range(0x21, 0x7F)] + ['…', '♥', '♪', '\x01', '\x02']
SPACE = 4                      # advance of ' '
WIDTH_OVERRIDE = {'\x02': 2}  # \x01 / \x02: blank 1 / 2 px spacers (name entry grid cells)


def parse():
    glyphs = {}
    lines = [s for s in _ART.strip('\n').splitlines()]
    for i in range(0, len(lines), 2):
        ch = eval(lines[i])
        rows = lines[i + 1].split('|')
        if len(rows) != 12:
            raise ValueError(f'{ch!r}: {len(rows)} rows')
        glyphs[ch] = rows
    return glyphs


def glyph(ch, g=None):
    """(12 bytes, advance) of a character."""
    g = g or parse()
    rows = g.get(ch, ['......'] * 12)
    ink = [x for r in rows for x, c in enumerate(r[:8]) if c == '#']
    left = min(ink) if ink else 0
    right = max(ink) - left if ink else -1
    out = bytearray()
    for r in rows:
        b = 0
        for x, c in enumerate(r[:8]):
            if c == '#':
                b |= 0x80 >> (x - left)
        out.append(b)
    adv = SPACE if ch == ' ' else right + 2
    return bytes(out), WIDTH_OVERRIDE.get(ch, adv)


def sheet(path, text=None):
    from PIL import Image
    g = parse()
    text = text or ''.join(CHARS)
    x = y = 0
    im = Image.new('L', (8 * 40, 14 * ((len(text) // 40) + 2)), 40)
    for ch in text:
        data, adv = glyph(ch, g)
        if x + adv > im.width or ch == '\n':
            x, y = 0, y + 14
        if ch == '\n':
            continue
        for r in range(12):
            for c in range(8):
                if data[r] & (0x80 >> c):
                    im.putpixel((x + c, y + r), 255)
        x += adv
    im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(path)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) >= 2 and argv[0] == 'sheet':
        sheet(argv[1], argv[2] if len(argv) > 2 else None)
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
